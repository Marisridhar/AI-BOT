import React from 'react';
import {
  Award,
  CheckCircle,
  AlertTriangle,
  ArrowRight,
  RefreshCw,
  Sparkles,
  TrendingUp,
  FileCode
} from 'lucide-react';

export const ReviewFeedback = ({ reviewData, onNavigate }) => {
  if (!reviewData) {
    return (
      <div className="card" style={{ textAlign: 'center', padding: '48px 20px' }}>
        <Award size={48} color="var(--primary)" style={{ marginBottom: '12px' }} />
        <h3 style={{ fontSize: '1.2rem', fontWeight: 600 }}>No Review Selected</h3>
        <p style={{ color: 'var(--text-secondary)', marginTop: '4px' }}>
          Submit an assignment first to view your detailed AI-powered evaluation report.
        </p>
        <button
          className="btn btn-primary"
          style={{ marginTop: '16px' }}
          onClick={() => onNavigate('student-dashboard')}
        >
          Go to Dashboard
        </button>
      </div>
    );
  }

  const isApproved = reviewData.decision === 'approved' || reviewData.score >= 70;
  const scoreColor = reviewData.score >= 70 ? 'var(--success)' : reviewData.score >= 50 ? 'var(--warning)' : 'var(--danger)';

  return (
    <div>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '20px' }}>
        <div>
          <h1 style={{ fontSize: '1.6rem', fontWeight: 700, display: 'flex', alignItems: 'center', gap: '8px' }}>
            <Award size={24} color={scoreColor} />
            <span>Evaluation Report &amp; Feedback</span>
          </h1>
          <p style={{ color: 'var(--text-secondary)', fontSize: '0.92rem' }}>
            Detailed breakdown generated by Gemini AI static evaluation.
          </p>
        </div>

        <div style={{ display: 'flex', gap: '10px' }}>
          <button className="btn btn-secondary" onClick={() => onNavigate('student-dashboard')}>
            Dashboard
          </button>
          {!isApproved ? (
            <button className="btn btn-primary" onClick={() => onNavigate('assignment-workspace')}>
              <RefreshCw size={16} /> Revise Submission
            </button>
          ) : (
            <button className="btn btn-success" onClick={() => onNavigate('learning-path')}>
              <span>Next Learning Stage</span>
              <ArrowRight size={16} />
            </button>
          )}
        </div>
      </div>

      {/* Top Score Banner */}
      <div
        className="card"
        style={{
          borderLeft: `6px solid ${scoreColor}`,
          padding: '24px',
          display: 'flex',
          justifyContent: 'space-between',
          alignItems: 'center'
        }}
      >
        <div>
          <div style={{ display: 'flex', alignItems: 'center', gap: '10px' }}>
            <span style={{ fontSize: '2.5rem', fontWeight: 800, color: scoreColor }}>
              {reviewData.score}/100
            </span>
            <span
              className="badge"
              style={{
                fontSize: '0.9rem',
                padding: '6px 12px',
                background: isApproved ? 'var(--success-bg)' : 'var(--warning-bg)',
                color: isApproved ? 'var(--success-text)' : 'var(--warning-text)'
              }}
            >
              {isApproved ? 'APPROVED' : 'NEEDS REVISION'}
            </span>
          </div>
          <p style={{ fontSize: '1rem', color: 'var(--text-primary)', marginTop: '8px', maxWidth: '700px' }}>
            {reviewData.summary}
          </p>
        </div>

        <div style={{ textAlign: 'right' }}>
          <div style={{ fontSize: '0.82rem', color: 'var(--text-muted)' }}>EVALUATION MODE</div>
          <div style={{ fontWeight: 600, fontSize: '0.92rem', color: 'var(--primary)', marginTop: '2px' }}>
            {reviewData.reviewMode || 'Gemini Static Analysis'}
          </div>
        </div>
      </div>

      {/* Rubric Criteria Breakdown */}
      <div className="card">
        <h3 className="card-title" style={{ marginBottom: '16px' }}>Rubric Score Breakdown</h3>
        <div style={{ display: 'flex', flexDirection: 'column', gap: '12px' }}>
          {reviewData.criterionScores?.map((crit, idx) => (
            <div
              key={idx}
              style={{
                border: '1px solid var(--border)',
                borderRadius: 'var(--radius-sm)',
                padding: '12px 16px',
                background: '#fff'
              }}
            >
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '6px' }}>
                <span style={{ fontWeight: 600, fontSize: '0.95rem' }}>{crit.criterion}</span>
                <span style={{ fontWeight: 700, color: 'var(--primary)' }}>
                  {crit.score} / {crit.maxScore}
                </span>
              </div>
              <p style={{ fontSize: '0.88rem', color: 'var(--text-secondary)', margin: 0 }}>
                {crit.feedback}
              </p>
            </div>
          ))}
        </div>
      </div>

      {/* Strengths & Issues Grid */}
      <div className="grid-cols-2">
        {/* Strengths */}
        <div className="card">
          <h3 className="card-title" style={{ display: 'flex', alignItems: 'center', gap: '8px', color: 'var(--success)' }}>
            <CheckCircle size={18} />
            <span>Key Strengths</span>
          </h3>
          <ul style={{ paddingLeft: '20px', marginTop: '12px', fontSize: '0.9rem', color: 'var(--text-primary)', lineHeight: 1.7 }}>
            {reviewData.strengths?.map((str, i) => (
              <li key={i}>{str}</li>
            ))}
          </ul>
        </div>

        {/* Areas for Improvement */}
        <div className="card">
          <h3 className="card-title" style={{ display: 'flex', alignItems: 'center', gap: '8px', color: 'var(--danger)' }}>
            <AlertTriangle size={18} />
            <span>Identified Improvements</span>
          </h3>

          <div style={{ display: 'flex', flexDirection: 'column', gap: '12px', marginTop: '12px' }}>
            {reviewData.issues?.map((iss, i) => (
              <div key={i} style={{ background: '#fef2f2', padding: '10px 12px', borderRadius: '4px', fontSize: '0.85rem' }}>
                <div style={{ fontWeight: 600, color: 'var(--danger-text)' }}>
                  [{iss.severity?.toUpperCase()}] {iss.criterion}: {iss.suggestion}
                </div>
                {iss.evidence && (
                  <div style={{ fontSize: '0.78rem', color: '#7f1d1d', marginTop: '4px' }}>
                    Evidence: {iss.evidence}
                  </div>
                )}
              </div>
            ))}
          </div>
        </div>
      </div>

      {/* Next Steps */}
      {reviewData.nextSteps && reviewData.nextSteps.length > 0 && (
        <div className="card">
          <h3 className="card-title" style={{ display: 'flex', alignItems: 'center', gap: '8px', color: 'var(--primary)' }}>
            <Sparkles size={18} />
            <span>Recommended Next Steps</span>
          </h3>
          <ul style={{ paddingLeft: '20px', marginTop: '10px', fontSize: '0.9rem', color: 'var(--text-primary)', lineHeight: 1.7 }}>
            {reviewData.nextSteps.map((step, i) => (
              <li key={i}>{step}</li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
};

export default ReviewFeedback;

